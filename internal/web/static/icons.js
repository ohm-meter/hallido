/**
 * Erzeugt ein inline Lucide-SVG (stroke, currentColor).
 * @param {string} name — Schlüssel in LUCIDE_PATHS (Dateiname ohne .svg)
 * @param {string} [className]
 * @returns {SVGSVGElement}
 */
function createLucideIcon(name, className) {
  const paths = LUCIDE_PATHS[name];
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  if (className) svg.setAttribute("class", className);
  if (paths) svg.innerHTML = paths;
  return svg;
}

/** Ersetzt [data-lucide]-Platzhalter im statischen Markup durch SVG. */
function initLucideIcons() {
  document.querySelectorAll("[data-lucide]").forEach((el) => {
    const name = el.getAttribute("data-lucide");
    if (!name) return;
    el.replaceWith(createLucideIcon(name, el.getAttribute("class") || "lucide-icon"));
  });
}

initLucideIcons();
